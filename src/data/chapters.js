// 에필로그 영상 대본. 오프닝처럼 나레이션과 해무의 말을 나눠 보여 준다.
// 표시 시간은 글자 수로 계산한다(초당 6.5자 + 1.2초). 긴 대사가 다 읽히기 전에 다음 장면으로 넘어가지 않도록, 연출의 기준 시각(at)도 대본에서 함께 계산해 Epilogue3D에 넘긴다.
//   네 섬을 마친 내 앞으로 해무가 날아와 내려앉고 → 이십 년 묵은 편지의 이유를 털어놓고 → 나에게 깨달음을 건네고 → 내가 옆의 편지섬으로 날아가 착륙(카메라는 섬을 중앙에 두고 클로즈업) → 편지 쓰기
export const EPILOGUE_PLAYBACK = 0.8;        // 재생 속도(오프닝과 같다). 대본의 시간은 이 속도에서의 초 단위다.
// 대사 목록 → 자막. 표시 시간은 글자 수로 계산한다(초당 6.5자 + 1.2초, 최소 min초). 줄 끝의 숫자는 그 줄만의 최소 시간(짧은 효과음 자막용)이다.
function layout(L, min = 4.5) {
  const GAP = 0.6;
  let cursor = 0.8;
  return L.map(([kind, text, minOne]) => {
    const dur = Math.max(minOne ?? min, EPILOGUE_PLAYBACK * (1.2 + text.length / 6.5));
    const c = kind === "s" ? { t: cursor, end: cursor + dur, who: "해무", text } : { t: cursor, end: cursor + dur, text };
    cursor += dur + GAP;
    return c;
  });
}
