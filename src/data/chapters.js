// 편지 네 통. 순서가 곧 장의 순서이고, 섬에서 섬으로 이어진다.
export function buildLetters() {
  return CHAPTERS.map((c, i) => {
    const prev = CHAPTERS[i - 1], next = CHAPTERS[i + 1];
    const link = next ? `바람이 ${next.island} 쪽으로 방향을 틀었다. 이제 ${next.who}에게 갈 차례다.` : "네 섬이 바람길로 하나가 되었다.";
    return {
      id: `l${i + 1}`, chapter: i + 1,
      from: prev ? prev.island : HOME_ISLAND, to: c.island,
      who: c.who, relation: c.relation,
      people: `${c.sender} → ${c.who}`,
      title: c.title,
      context: `${i + 1}장. ${c.context}${prev ? ` 앞 장에서 ${prev.who}에게 편지가 닿으며, ${c.island}로 가는 바람길이 열렸습니다.` : " 해무가 열어 준 첫 바람길입니다."}`,
      memo: `${c.memo} ${WIND_LINE[c.wind]}`,
      memory: c.memory,
      body: c.body,
      reply: `편지가 ${c.island}에 닿았다. ${c.arrive} ${link}`,
      flight: { ...FLIGHT_BY_GAP[c.wind], ...FLIGHT_COMMON, skyWalk: i >= 2 },    // 3장부터 하늘길 걷기
    };
  });
}

