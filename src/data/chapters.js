// 한국어 조사 붙이기: josa("도윤", "이", "가") → "도윤이", josa("서하", "이", "가") → "서하가"
const hasBatchim = (w) => {
  const c = (w || "").trim().slice(-1).charCodeAt(0);
  return c >= 0xac00 && c <= 0xd7a3 && (c - 0xac00) % 28 !== 0;
};
export const josa = (w, withB, withoutB) => w + (hasBatchim(w) ? withB : withoutB);

